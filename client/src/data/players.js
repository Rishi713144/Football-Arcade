export const orderForRarity = (rarity) => (RARITIES[rarity] ? RARITIES[rarity].order : 99);

export function sortPlayers(list = players) {
  return [...list].sort((a, b) => a.overall - b.overall || orderForRarity(a.rarity) - orderForRarity(b.rarity));
}

// Fisher-Yates
export function shuffle(list) {
  const copy = [...list];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

export function picksOf(count = 5, from = players) {
  return shuffle(from).slice(0, count);
}

export function avgOverall(list) {
  if (!list.length) return 0;
  return Math.round(list.reduce((sum, p) => sum + p.overall, 0) / list.length);
}

export function squadChemistry(list) {
  let total = 0;
  for (let i = 0; i < list.length; i++) {
    for (let j = i + 1; j < list.length; j++) {
      const a = list[i];
      const b = list[j];

      if (a.id === b.id) continue;
      if (a.club === b.club) total += 3;
      else if (a.nation === b.nation) total += 2;
      else if (a.league === b.league) total += 1;
      // Icons & Legends link with everyone
      if (a.rarity === 'Legend' || a.rarity === 'Icon') total += 1;
      if (b.rarity === 'Legend' || b.rarity === 'Icon') total += 1;
    }
  }
  return total;
}

export function chemistryGrade(chem, size) {
  const max = size * (size - 1) * 3;
  const ratio = chem / (max || 1);
  if (ratio >= 0.55) return { letter: 'S', color: '#ffd700', label: 'Perfect chemistry flow' };
  if (ratio >= 0.4) return { letter: 'A', color: '#39ff14', label: 'Strong links' };
  if (ratio >= 0.25) return { letter: 'B', color: '#00ffff', label: 'Growing chemistry' };
  if (ratio >= 0.12) return { letter: 'C', color: '#ffd27d', label: 'Mixed links' };
  return { letter: 'D', color: '#ff6b6b', label: 'Disconnected club' };
}

export function effectiveRating(list) {
  const overall = avgOverall(list);
  const chem = squadChemistry(list);
  const bonus = Math.min(5, Math.floor(chem / Math.max(1, list.length)));
  return { overall, chem, bonus, effective: Math.min(99, overall + bonus) };
}

export function formationFrom(list) {
  const fw = list.filter(p => ['ST', 'CF', 'LW', 'RW'].includes(p.position)).length;
  const mf = list.filter(p => ['CM', 'CAM', 'CDM'].includes(p.position)).length;
  const df = list.filter(p => ['CB', 'LB', 'RB', 'GK'].includes(p.position)).length;
  const label = `${Math.max(1, df)}-${Math.max(1, mf)}-${Math.max(1, fw)}`;
  return { label, fw, mf, df };
}